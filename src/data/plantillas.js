// Genera el link de WhatsApp con contexto completo.
// El id de la plantilla en el mensaje es crítico: es cómo el fundador
// sabe exactamente qué vio el cliente.
export function buildPlantillaWhatsappLink({ plantillaId, plantillaNombre, eventoNombre, paqueteNombre }) {
  const texto = `Hola, vi la plantilla ${plantillaNombre} (ref: ${plantillaId}) para mi ${eventoNombre}. Me interesa el paquete ${paqueteNombre}. ¿Me pueden dar más información?`
  return `https://wa.me/529932228936?text=${encodeURIComponent(texto)}`
}
